<?php

declare(strict_types=1);

use Tests\Support\GuestScripts;

it('copies regular guest scripts and siblings with permissions while ignoring generated directories', function (): void {
    $source = temporaryPath('orbit-guest-sources-');
    mkdir($source.'/__pycache__', 0o700, true);
    file_put_contents($source.'/__pycache__/control.pyc', 'generated bytecode');
    file_put_contents($source.'/entry.sh', "#!/usr/bin/env bash\n/usr/bin/php -r 'echo 1;'\n");
    chmod($source.'/entry.sh', 0o750);
    file_put_contents($source.'/sibling.py', "print('sibling')\n");
    chmod($source.'/sibling.py', 0o640);

    $path = GuestScripts::path('entry.sh', $source);

    expect(scandir(dirname($path)))->toBe(['.', '..', 'entry.sh', 'sibling.py']);
    expect(file_get_contents($path))->toBe("#!/usr/bin/env bash\n".escapeshellarg(PHP_BINARY)." -r 'echo 1;'\n");
    expect(fileperms($path) & 0o777)->toBe(0o750);
    expect(file_get_contents(dirname($path).'/sibling.py'))->toBe("print('sibling')\n");
    expect(fileperms(dirname($path).'/sibling.py') & 0o777)->toBe(0o640);
    expect(file_get_contents($source.'/__pycache__/control.pyc'))->toBe('generated bytecode');
});

it('rejects a requested guest script that is missing or a directory', function (string $name): void {
    $source = temporaryPath('orbit-guest-missing-');
    mkdir($source.'/__pycache__', 0o700, true);
    file_put_contents($source.'/sibling.sh', "#!/usr/bin/env bash\nexit 0\n");

    expect(fn (): string => GuestScripts::path($name, $source))
        ->toThrow(RuntimeException::class, "The guest script {$name} does not exist.");
})->with(['missing.sh', '__pycache__']);
